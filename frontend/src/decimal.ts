/** Ввод дробных чисел: на русской раскладке и на мобильной клавиатуре
 *  разделитель — запятая, а Number("0,5") — это NaN.
 *
 *  Нормализуем прямо при вводе, а не при отправке: значение поля лежит в
 *  состоянии строкой, и по нему же считаются подсказки («≈ цена за грамм»).
 *  Без этого «0,5» молча превращался в NaN, строка тех карты отбрасывалась
 *  фильтром, и карта сохранялась пустой. */
export function decimalInput(value: string): string {
  return value.replace(",", ".");
}
