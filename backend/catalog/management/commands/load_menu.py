class Command(BaseCommand):
    help = "Загрузить актуальное меню кафе (идемпотентно)"

    @transaction.atomic
    def handle(self, *args, **options):
        seen_categories, seen_products = [], []

        for cat_order, (cat_name, items) in enumerate(MENU, start=1):
            category, _ = Category.objects.update_or_create(
                name=cat_name,
                defaults={"sort_order": cat_order, "is_active": True},
            )
            seen_categories.append(category.pk)

            for item_order, (name, price, description) in enumerate(items, start=1):
                product, _ = Product.objects.update_or_create(
                    category=category,
                    name=name,
                    defaults={
                        "price": Decimal(price),
                        "description": description,
                        # сквозная нумерация, чтобы вкладка «Все» шла в порядке меню
                        "sort_order": cat_order * 100 + item_order,
                        # в печатном меню объёмов нет — чистим остатки демо-данных
                        "weight_grams": None,
                        "is_available": True,
                    },
                )
                seen_products.append(product.pk)

        self._retire_old(seen_categories, seen_products)

        self.stdout.write(
            self.style.SUCCESS(
                f"Меню загружено: {len(seen_categories)} категорий, "
                f"{len(seen_products)} позиций"
            )
        )

    def _retire_old(self, seen_categories: list[int], seen_products: list[int]):
        """Убрать позиции и категории, которых больше нет в меню."""
        removed, hidden = 0, 0
        for product in Product.objects.exclude(pk__in=seen_products):
            try:
                with transaction.atomic():
                    product.delete()
                    removed += 1
            except ProtectedError:
                # на позицию есть заказы — историю не рвём, просто прячем
                Product.objects.filter(pk=product.pk).update(is_available=False)
                hidden += 1

        stale = Category.objects.exclude(pk__in=seen_categories)
        for category in stale:
            try:
                with transaction.atomic():
                    category.delete()
            except ProtectedError:
                Category.objects.filter(pk=category.pk).update(is_active=False)

        if removed or hidden:
            self.stdout.write(
                self.style.WARNING(
                    f"Старых позиций удалено: {removed}, скрыто (есть заказы): {hidden}"
                )
            )
